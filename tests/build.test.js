import test from 'node:test';
import assert from 'node:assert/strict';
import { access, readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';

test('el build publica los módulos del navegador en dist/assets', async () => {
  const result = spawnSync(process.execPath, ['scripts/build.mjs'], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  await access('dist/assets/app.js');
  await access('dist/assets/core/trace-parser.js');
  await access('dist/assets/miners/alpha-miner.js');
  await access('dist/assets/ui/svg-renderer.js');
  const html = await readFile('dist/index.html', 'utf8');
  const app = await readFile('dist/assets/app.js', 'utf8');
  const styles = await readFile('dist/learning.css', 'utf8');
  assert.match(html, /src="\.\/assets\/app\.js"/);
  assert.match(app, /Directly Follows/);
  assert.match(app, /direct-evidence/);
  assert.match(app, /Cómo se obtiene/);
  assert.match(styles, /\.direct-evidence/);
  assert.match(html, /href="\.\/learning\.css"/);
  assert.match(app, /lesson-help/);
  assert.match(app, /Error frecuente/);
  assert.match(app, /alpha-glossary/);
  assert.match(app, /network-origin/);
  assert.match(app, /Dimensiones de conformidad/);
  assert.match(app, /Limitaciones de Alpha clásico/);
  assert.match(app, /Descubrir el proceso, no copiar las trazas/);
  assert.match(app, /Correspondencia con la definición formal/);
  assert.match(app, /Comprobación del resultado/);
  assert.match(app, /Equivalencia gráfica/);
  assert.match(app, /Cada lugar derivado corresponde a un elemento de Y/);
  assert.match(styles, /\.lesson-help/);
  assert.match(styles, /\.conformance-grid/);
  assert.match(styles, /\.limitation-grid/);
  assert.match(styles, /\.canonical-checks/);
  assert.match(styles, /\.network-equivalence/);
  const renderer = await readFile('dist/assets/ui/svg-renderer.js', 'utf8');
  assert.match(renderer, /onNodeSelect/);
  assert.match(renderer, /arc--spine/);
  assert.match(renderer, /arc--branch/);
  assert.match(renderer, /arc--return/);
});
